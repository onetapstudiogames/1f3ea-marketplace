#!/usr/bin/env node
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { join } from 'node:path'
import { parseListings } from './lib/listings.mjs'

const root = fileURLToPath(new URL('..', import.meta.url))
const read = file => readFile(join(root, file), 'utf8')
const manifest = JSON.parse(await read('.codex-plugin/plugin.json'))
const claudeManifest = JSON.parse(await read('.claude-plugin/plugin.json'))
const mcp = JSON.parse(await read('.mcp.json'))
const readme = (await read('README.md')).replaceAll('\r\n', '\n')
const changelog = (await read('CHANGELOG.md')).replaceAll('\r\n', '\n')
const directories = parseListings(await read('docs/LISTINGS.md'))
const imagePath = manifest.interface.composerIcon.replace(/^\.\//u, '')
const logoPath = manifest.interface.logo.replace(/^\.\//u, '')

if (manifest.version !== claudeManifest.version || manifest.interface.displayName !== claudeManifest.displayName) {
  throw new Error('Plugin manifests disagree on version or display name')
}
if (manifest.interface.shortDescription.length > 30) throw new Error('Short description exceeds 30 characters')

async function imageInfo(path) {
  const bytes = await readFile(join(root, path))
  if (bytes.subarray(1, 4).toString() !== 'PNG') throw new Error(`${path} is not a PNG`)
  return {
    url: new URL('/og-image.png', manifest.homepage).href,
    path,
    width: bytes.readUInt32BE(16),
    height: bytes.readUInt32BE(20),
    bytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
  }
}

function fencedAfter(heading) {
  const section = readme.split(`### ${heading}\n`)[1]?.split('\n### ')[0]
  const code = section?.match(/```text\s*\n([^`]+)```/u)?.[1]?.trim()
  if (!code) throw new Error(`README.md has no ${heading} install block`)
  return code
}

const firstChange = changelog.match(/^## \[2\.4\.6\][^\n]*\n\s*\n- ([^\n]+)/mu)?.[1]
const imageChange = changelog.match(/^## \[2\.4\.4\][^\n]*\n\s*\n- ([^\n]+)/mu)?.[1]
if (!firstChange || !imageChange) throw new Error('CHANGELOG.md is missing join or illustration changes')
const changedSinceFirstVersion = [firstChange, imageChange]
  .map(text => text.trim().replace(/^B7 join-2: add/u, 'Add').match(/^.*?\.(?=\s|$)/u)?.[0])
  .join(' ')
const positioningLine = manifest.interface.longDescription.split(/\.\s/u)[0] + '.'
const codexSteps = readme.split('### Codex\n')[1]?.match(/```text[\s\S]+?```\n\n([^\n]+)\n/u)?.[1]
if (!codexSteps) throw new Error('README.md has no Codex install follow-up')

const metadata = {
  displayName: manifest.interface.displayName,
  shortDescription: manifest.interface.shortDescription,
  longDescription: manifest.interface.longDescription,
  positioningLine,
  version: manifest.version,
  images: { icon: await imageInfo(imagePath), logo: await imageInfo(logoPath) },
  links: {
    website: manifest.homepage,
    privacy: manifest.interface.privacyPolicyURL,
    terms: manifest.interface.termsOfServiceURL,
    support: manifest.interface.supportURL,
    repository: manifest.repository,
    connector: mcp.mcpServers['1f3ea'].url,
  },
  install: { claudeCode: fencedAfter('Claude Code'), codex: `${fencedAfter('Codex')}\n${codexSteps}` },
  keywords: ['AI agent marketplace', 'MCP server', 'USDC', 'sell to agents', 'Claude Code plugin'],
  directories,
}

const kit = `# 1F3EA listing kit\n\n> Status: current\n\nGenerated by \`node scripts/generate-listing-kit.mjs\` from the manifests, README, CHANGELOG, image assets, and [listing ledger](LISTINGS.md). Edit those sources, then regenerate.\n\n| Field | Current listing text |\n| --- | --- |\n| Display name | ${metadata.displayName} |\n| Short description (${metadata.shortDescription.length}/30 characters) | ${metadata.shortDescription} |\n| Positioning line | ${metadata.positioningLine} |\n| Version | ${metadata.version} |\n\n## Long description\n\n${metadata.longDescription}\n\n## Images\n\n| Use | Public image URL | Source file | Dimensions | File size | SHA-256 |\n| --- | --- | --- | --- | --- | --- |\n| Icon | ${metadata.images.icon.url} | ${metadata.images.icon.path} | ${metadata.images.icon.width} × ${metadata.images.icon.height} | ${metadata.images.icon.bytes} bytes | ${metadata.images.icon.sha256} |\n| Logo | ${metadata.images.logo.url} | ${metadata.images.logo.path} | ${metadata.images.logo.width} × ${metadata.images.logo.height} | ${metadata.images.logo.bytes} bytes | ${metadata.images.logo.sha256} |\n\n## Links\n\n| Website | Privacy | Terms | Support | Repository | Connector |\n| --- | --- | --- | --- | --- | --- |\n| ${Object.values(metadata.links).join(' | ')} |\n\n## Install in Claude Code\n\n\`\`\`text\n${metadata.install.claudeCode}\n\`\`\`\n\n## Install in Codex\n\n\`\`\`text\n${fencedAfter('Codex')}\n\`\`\`\n\n${codexSteps}\n\n## Search phrases\n\n${metadata.keywords.map(word => `- ${word}`).join('\n')}\n\n## What changed since the first version\n\n${changedSinceFirstVersion}\n\nDirectory locations and their verification state are in [LISTINGS.md](LISTINGS.md).\n`

const outputs = {
  'docs/listing-metadata.json': JSON.stringify(metadata, null, 2) + '\n',
  'docs/LISTING-KIT.md': kit,
}
for (const [path, content] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    const existing = await read(path).catch(() => '')
    if (existing !== content) throw new Error(`${path} is stale; run node scripts/generate-listing-kit.mjs`)
  } else {
    await writeFile(join(root, path), content)
  }
}
